#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";

const DEFAULT_REPOSITORY = "k1muza/feedsport";
const DEFAULT_REF = "feature/brazilian-swine-import";
const DEFAULT_SHARD_SIZE = 20;
const INGREDIENTS_PATH = "src/data/ingredients.json";
const NUTRIENTS_PATH = "src/data/nutrients.json";

function readArgs(argv) {
  const args = {
    repository: DEFAULT_REPOSITORY,
    ref: DEFAULT_REF,
    shardSize: DEFAULT_SHARD_SIZE,
  };

  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === "--repository") args.repository = argv[++index];
    else if (arg === "--ref") args.ref = argv[++index];
    else if (arg === "--shard-size") args.shardSize = Number(argv[++index]);
    else throw new Error(`Unknown argument: ${arg}`);
  }

  if (!Number.isInteger(args.shardSize) || args.shardSize <= 0) {
    throw new Error("--shard-size must be a positive integer.");
  }
  return args;
}

function githubHeaders() {
  const headers = {
    Accept: "application/vnd.github+json",
    "User-Agent": "pigflow-feedsport-importer",
    "X-GitHub-Api-Version": "2022-11-28",
  };
  if (process.env.GITHUB_TOKEN) {
    headers.Authorization = `Bearer ${process.env.GITHUB_TOKEN}`;
  }
  return headers;
}

async function fetchJson(url, headers = {}) {
  const response = await fetch(url, { headers });
  if (!response.ok) {
    throw new Error(`GET ${url} failed: ${response.status} ${response.statusText}`);
  }
  return response.json();
}

async function resolveCommit(repository, ref) {
  const encodedRef = encodeURIComponent(ref);
  const commit = await fetchJson(
    `https://api.github.com/repos/${repository}/commits/${encodedRef}`,
    githubHeaders(),
  );
  if (!commit?.sha) throw new Error(`Could not resolve ${repository}@${ref}.`);
  return commit.sha;
}

async function fetchSourceJson(repository, commit, sourcePath) {
  const encodedPath = sourcePath
    .split("/")
    .map((part) => encodeURIComponent(part))
    .join("/");
  return fetchJson(
    `https://raw.githubusercontent.com/${repository}/${commit}/${encodedPath}`,
  );
}

function writeJson(filePath, value) {
  fs.writeFileSync(filePath, JSON.stringify(value, null, 2) + "\n");
}

function writeCompactJson(filePath, value) {
  fs.writeFileSync(filePath, JSON.stringify(value) + "\n");
}

function generateSnapshotIndex(shardFiles) {
  const imports = shardFiles
    .map(
      (file, index) =>
        `import ingredients${String(index + 1).padStart(2, "0")} from "./ingredients/${file}";`,
    )
    .join("\n");
  const spreads = shardFiles
    .map((_, index) => `  ...ingredients${String(index + 1).padStart(2, "0")},`)
    .join("\n");

  return `// Generated by scripts/import-feedsport-ingredients.mjs. Do not edit by hand.
import manifest from "./manifest.json";
import nutrients from "./nutrients.json";
${imports}

export const feedSportManifestJson = manifest;
export const feedSportNutrientsJson = nutrients;
export const feedSportIngredientRowsJson = [
${spreads}
];
`;
}

async function main() {
  const args = readArgs(process.argv.slice(2));
  const root = process.cwd();
  const baseDir = path.join(root, "src/data/nutrition/feedsport");
  const ingredientDir = path.join(baseDir, "ingredients");

  const commit = await resolveCommit(args.repository, args.ref);
  const [ingredients, nutrients] = await Promise.all([
    fetchSourceJson(args.repository, commit, INGREDIENTS_PATH),
    fetchSourceJson(args.repository, commit, NUTRIENTS_PATH),
  ]);

  if (!Array.isArray(ingredients) || !Array.isArray(nutrients)) {
    throw new Error("FeedSport ingredient and nutrient sources must both be JSON arrays.");
  }

  fs.mkdirSync(ingredientDir, { recursive: true });
  for (const file of fs.readdirSync(ingredientDir)) {
    if (/^ingredients-\d+\.json$/.test(file)) {
      fs.rmSync(path.join(ingredientDir, file));
    }
  }

  const shardFiles = [];
  for (let start = 0; start < ingredients.length; start += args.shardSize) {
    const number = String(Math.floor(start / args.shardSize) + 1).padStart(2, "0");
    const file = `ingredients-${number}.json`;
    writeCompactJson(
      path.join(ingredientDir, file),
      ingredients.slice(start, start + args.shardSize),
    );
    shardFiles.push(file);
  }

  writeJson(path.join(baseDir, "nutrients.json"), nutrients);

  const nutrientIds = new Set(nutrients.map((nutrient) => String(nutrient.id)));
  const swineNutrientIds = new Set(
    [...nutrientIds].filter((id) => id.startsWith("swine-") || id.startsWith("sow-")),
  );
  const unresolvedNutrientIds = [
    ...new Set(
      ingredients.flatMap((ingredient) =>
        (ingredient.compositions ?? [])
          .map((composition) => String(composition.nutrientId))
          .filter((id) => !nutrientIds.has(id)),
      ),
    ),
  ].sort();
  const ingredientsWithSwineData = ingredients.filter((ingredient) =>
    (ingredient.compositions ?? []).some((composition) =>
      swineNutrientIds.has(String(composition.nutrientId)),
    ),
  ).length;

  const manifest = {
    schemaVersion: 1,
    id: "feedsport-ingredient-snapshot",
    source: {
      repository: args.repository,
      ref: args.ref,
      commit,
      ingredientsPath: INGREDIENTS_PATH,
      nutrientsPath: NUTRIENTS_PATH,
    },
    basisPolicy:
      "Composition entries retain FeedSport nutrient IDs, values, table/source labels and basis verbatim.",
    ingredientCount: ingredients.length,
    nutrientCount: nutrients.length,
    swineNutrientCount: swineNutrientIds.size,
    ingredientsWithSwineData,
    shardSize: args.shardSize,
    ingredientShards: shardFiles,
    unresolvedNutrientIds,
  };
  writeJson(path.join(baseDir, "manifest.json"), manifest);
  fs.writeFileSync(path.join(baseDir, "snapshot.ts"), generateSnapshotIndex(shardFiles));

  console.log(
    JSON.stringify(
      {
        repository: args.repository,
        ref: args.ref,
        commit,
        ingredientCount: ingredients.length,
        nutrientCount: nutrients.length,
        swineNutrientCount: swineNutrientIds.size,
        ingredientsWithSwineData,
        unresolvedNutrientIds,
        shards: shardFiles.length,
      },
      null,
      2,
    ),
  );
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
